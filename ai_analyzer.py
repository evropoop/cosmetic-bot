async def generate_diagnosis(name: str, tags: list) -> str:
    """Генерирует короткий диагноз (строго до 400 символов)."""
    tags_str = ", ".join(tags) if tags else "нет тегов"

    # ===== ОПРЕДЕЛЯЕМ ПЕРСОНАЛЬНЫЕ ТЕГИ =====
    has_allergy = any(t.startswith("allergy_") for t in tags)
    has_medicine = "medicine" in tags
    has_pregnancy = "pregnancy" in tags

    personal_note = ""
    if has_allergy or has_medicine or has_pregnancy:
        personal_note = "\n\n⚠️ ВАЖНО: у клиентки есть персональные теги (аллергия / медицина / беременность). ОБЯЗАТЕЛЬНО вплети их в диагноз одной короткой фразой."

    user_prompt = f"""Имя клиентки: {name}
Теги из анкеты: [{tags_str}]{personal_note}

Выдай короткое резюме СТРОГО до 400 символов (включая пробелы и знаки препинания) по формуле экспертного диагноза из 4 шагов:
1. ФАКТ — констатация состояния кожи.
2. МЕХАНИКА — объяснение причины профессиональными терминами.
3. ПЕРСОНАЛИЗАЦИЯ — упоминание аллергий, беременности, препаратов (если есть в тегах).
4. СТРАТЕГИЯ — экспертный призыв к действию.

КРИТИЧЕСКИ ВАЖНО:
- Твой ответ НЕ ДОЛЖЕН превышать 400 символов.
- Прежде чем выдать ответ — мысленно посчитай символы.
- Если не укладываешься — сократи механику и стратегию, но СОХРАНИ все 4 шага.
- НИКОГДА не обрывай предложение на полуслове.
- Лучше короче, но с законченной мыслью.

Используй только профессиональную космецевтическую терминологию. Запрещены бытовые метафоры, просторечия и поэтические выражения. Одним абзацем, без списков."""

    try:
        response = await client.chat.completions.create(
            model="openai/gpt-4o-mini",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ],
            temperature=0.7,
            max_tokens=250,  # ← 250 токенов ≈ 400 символов
        )

        if not response or not response.choices:
            return f"{name}, анализ завершён. Я беру вашу ситуацию под контроль: наша задача — выстроить надёжный физиологичный фундамент."

        result = response.choices[0].message.content

        if not result:
            return f"{name}, анализ завершён. Я беру вашу ситуацию под контроль: наша задача — выстроить надёжный физиологичный фундамент."

        # ===== Страховка: если всё равно длиннее 400 =====
        if len(result) > 400:
            # Обрезаем по последнему пробелу перед 400-м символом
            cut = result[:400].rfind(" ")
            if cut > 300:
                result = result[:cut] + "..."
            else:
                result = result[:397] + "..."

        return result

    except Exception as e:
        logger.error(f"Ошибка в generate_diagnosis: {e}")
        return f"{name}, анализ завершён. Я беру вашу ситуацию под контроль: наша задача — выстроить надёжный физиологичный фундамент."
