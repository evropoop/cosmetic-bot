def _translate_tags(tags: list) -> str:
    """Переводит английские теги в русские для промпта."""
    if not tags:
        return "нет тегов"
    result = []
    for t in tags:
        if t.startswith("allergy_"):
            name = t[len("allergy_"):]
            result.append(f"Аллергия на {name}")
        elif t in TAG_MAP:
            result.append(TAG_MAP[t])
        else:
            result.append(t)
    return ", ".join(result)


