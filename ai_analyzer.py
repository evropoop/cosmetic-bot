async def analyze_composition(composition: str, tags: list, user_name: str = "") -> dict:
    """Отправляет состав в Polza.ai и возвращает вердикт (до 400 символов)."""
    tags_str = ", ".join(tags) if tags else "нет тегов"

    if len(composition) > 2000:
        composition = composition[:2000] + "..."

    user_prompt = f"""Имя клиентки: {user_name or 'не указано'}
Теги клиентки: [{tags_str}]

Состав: {composition}

Выдай вердикт строго по формату (вердикт + объяснение до 400 символов)."""

    response = await client.chat.completions.create(
        model="openai/gpt-4o-mini",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt}
        ],
        temperature=0.7,
        max_tokens=250,
    )

    result = response.choices[0].message.content

    # Обрезаем до 400 символов на всякий случай
    if len(result) > 400:
        result = result[:397] + "..."

    if "🔴" in result:
        status = "bad"
    elif "🟠" in result:
        status = "hidden_threat"
    elif "🟡" in result:
        status = "conditional"
    elif "🟢" in result:
        status = "good"
    elif "⚪" in result:
        status = "neutral"
    elif "🔵" in result:
        status = "hydrophilic"
    else:
        status = "unknown"

    return {"verdict": result, "status": status}


async def generate_diagnosis(name: str, tags: list) -> str:
    """Генерирует короткий диагноз (до 400 символов) на основе тегов."""
    tags_str = ", ".join(tags) if tags else "нет тегов"

    user_prompt = f"""Имя клиентки: {name}
Теги из анкеты: [{tags_str}]

Выдай короткое резюме (до 400 символов): обратись по имени, опиши состояние кожи на основе тегов, объясни причину и возьми ситуацию под контроль. Без списков, одним абзацем."""

    response = await client.chat.completions.create(
        model="openai/gpt-4o-mini",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt}
        ],
        temperature=0.7,
        max_tokens=200,
    )

    result = response.choices[0].message.content
    if len(result) > 400:
        result = result[:397] + "..."
    return result
