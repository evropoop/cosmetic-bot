def _get_status(result: str) -> str:
    if "🔴" in result:
        return "bad"
    elif "🟠" in result:
        return "hidden_threat"
    elif "🟡" in result:
        return "conditional"
    elif "🟢" in result:
        return "good"
    elif "⚪" in result:
        return "neutral"
    elif "🔵" in result:
        return "hydrophilic"
    else:
        return "unknown"


def _safe_trim(text: str, limit: int = 400) -> str:
    """Умная обрезка текста по последнему предложению."""
    if len(text) <= limit:
        return text

    cut = text[:limit].rfind(".")
    if cut > 200:
        return text[:cut + 1]

    cut = text[:limit].rfind(" ")
    if cut > 200:
        return text[:cut]

    return text[:limit]


