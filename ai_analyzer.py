async def analyze_composition(composition: str, tags: list) -> dict:
    """Отправляет состав в Polza.ai и возвращает вердикт."""
    tags_str = ", ".join(tags) if tags else "нет тегов"

    if len(composition) > 2000:
        composition = composition[:2000] + "..."

    user_prompt = f"""Теги клиентки: [{tags_str}]

Состав: {composition}

Выдай вердикт строго по формату (вердикт + 2-3 абзаца объяснения)."""

    response = await client.chat.completions.create(
        model="openai/gpt-4o-mini",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt}
        ],
        temperature=0.7,
        max_tokens=500,
    )

    result = response.choices[0].message.content

    # Определяем статус по эмодзи
    if "🔴" in result:
        status = "bad"
    elif "🟠" in result:
        status = "hidden_threat"
    elif "🟡" in result:
        status = "conditional"
    elif "🟢" in result:
        status = "good"
    elif "⚪" in result:
        status = "neutral"
    elif "🔵" in result:
        status = "hydrophilic"
    else:
        status = "unknown"

    return {"verdict": result, "status": status}
