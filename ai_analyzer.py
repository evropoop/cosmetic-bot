            status_emoji = "🟢"
            stage_tag = "Базовый крем"
            actives_tag = "Увлажнение и поддержка барьера тела"
            logger.warning(f"🟢 BODY OVERRIDE: {status_emoji_original if 'status_emoji_original' in dir() else 'neutral/conditional'} → forced good")
