# ================== ОПРЕДЕЛЕНИЕ СТАТУСА ==================
def _get_status(result: str) -> str:
    if "🔴" in result:
        return "bad"
    elif "🟠" in result:
        return "hidden_threat"
    elif "🟡" in result:
        return "conditional"
    elif "🟢" in result:
        return "good"
    elif "⚪" in result:
        return "neutral"
    elif "🔵" in result:
        return "hydrophilic"
    elif "⚠️" in result or "НЕДОСТАТОЧНО ДАННЫХ" in result:
        return "error"
    else:
        return "unknown"


# ================== ОБРЕЗКА + ЗАЩИТА ОТ ЭХА ==================
def _safe_trim(text: str, limit: int = 500) -> str:
    echo_markers = [
        "РОЛЬ И ТОНАЛЬНОСТЬ", "БЛОК 3", "ШАБЛОНЫ ДЛЯ СТАРТА",
        "МАТРИЦА", "ПРАВИЛО 1:", "БРОНЯ ОТ", "ПРИМЕРЫ ЭТАЛОННЫХ",
        "ДИАГНОСТИЧЕСКАЯ МАТРИЦА", "ЧАСТЬ"
    ]
    if any(marker in text[:400] for marker in echo_markers):
        for emoji in ["🔴", "🟠", "🟡", "🟢", "⚪", "🔵", "⚠️"]:
            idx = text.find(emoji)
            if idx != -1:
                pre = text[:idx]
                dot = pre.rfind(".")
                if dot != -1 and dot > 50:
                    text = text[dot + 1:].strip()
                else:
                    text = text[idx:]
                break
        else:
            return "⚠️ НЕДОСТАТОЧНО ДАННЫХ. Модель не выдала вердикт. Попробуйте ещё раз."

    if len(text) <= limit:
        return text

    cut = text[:limit].rfind(".")
    if cut > 250:
        return text[:cut + 1]

    cut = text[:limit].rfind(" ")
    if cut > 250:
        return text[:cut]

    return text[:limit]


# ================== ЯДРО: ВЫЗОВ МОДЕЛИ ==================
async def _call_llm(system_prompt: str, user_prompt: str, temperature: float) -> str:
    combined = f"""{system_prompt}

==========================
ДАННЫЕ ОТ КЛИЕНТА:
==========================
{user_prompt}

==========================
ЗАДАЧА:
==========================
Выдай ТОЛЬКО финальный ответ клиенту по шаблону из матрицы.
Первое слово — имя клиента. Далее статус (эмодзи + название) и 2-3 предложения химического разбора.
НЕ повторяй инструкции. НЕ выводи правила. НЕ копируй матрицу. НЕ пиши «Добрый день».
Максимум 500 символов."""

    try:
        response = await client.chat.completions.create(
            model=MODEL_NAME,
            messages=[{"role": "user", "content": combined}],
            temperature=temperature,
            max_tokens=MAX_TOKENS,
        )

        if not response or not response.choices:
            logger.error("Модель вернула пустой ответ")
            return ""

        usage = response.usage
        if usage:
            cached_tokens = 0
            try:
                if hasattr(usage, "prompt_tokens_details") and usage.prompt_tokens_details:
                    cached_tokens = getattr(usage.prompt_tokens_details, "cached_tokens", 0) or 0
                elif hasattr(usage, "cached_tokens"):
                    cached_tokens = usage.cached_tokens or 0
            except Exception:
                cached_tokens = 0

            logger.info(
                f"📊 Токены: вход={usage.prompt_tokens}, "
                f"из кэша={cached_tokens}, "
                f"выход={usage.completion_tokens}"
            )

        content = response.choices[0].message.content
        if not content:
            logger.error("Модель вернула пустой текст")
            return ""

        return content

    except Exception as e:
        logger.error(f"Ошибка вызова LLM: {e}")
        return ""


async def _call_llm_with_retry(system_prompt: str, user_prompt: str) -> dict:
    result_text = await _call_llm(system_prompt, user_prompt, TEMPERATURE_ANALYSIS)

    if result_text:
        result_text = _safe_trim(result_text, 500)
        status = _get_status(result_text)
        if status not in ["error", "unknown"]:
            return {"verdict": result_text, "status": status}

    logger.warning("Ретрай запроса к LLM (temperature=0)")
    retry_text = await _call_llm(system_prompt, user_prompt, 0.0)

    if retry_text:
        retry_text = _safe_trim(retry_text, 500)
        status = _get_status(retry_text)
        return {"verdict": retry_text, "status": status}

    return {
        "verdict": "⚠️ НЕДОСТАТОЧНО ДАННЫХ. Не удалось обработать состав. Попробуйте ещё раз — лимит не списан.",
        "status": "error"
    }


